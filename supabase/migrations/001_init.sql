-- CAEZAR PERFUMES: initial schema, security rules, order/stock functions, storage and seed data.
-- Run once in the Supabase SQL editor (or `supabase db push`). Safe to read top to bottom.

create type product_status as enum ('published', 'draft', 'out_of_stock');

-- ---------- tables ----------
create table profiles (
  id         uuid primary key references auth.users on delete cascade,
  role       text not null default 'customer' check (role in ('customer', 'admin')),
  full_name  text,
  phone      text,
  created_at timestamptz not null default now()
);

create table products (
  id             bigint generated by default as identity primary key,
  slug           text unique not null,
  name_en        text not null check (length(name_en) between 1 and 120),
  name_ar        text,
  description_en text,
  description_ar text,
  scent_type     text,
  volume_ml      int check (volume_ml > 0),
  size_label     text,                                   -- e.g. '3 × 50 ml' for sets
  price_egp      numeric(10,2) not null check (price_egp >= 0),
  stock          int check (stock >= 0),                 -- null = not tracked
  status         product_status not null default 'draft',
  badge_en       text,
  badge_ar       text,
  notes          jsonb not null default
    '{"top":{"en":[],"ar":[]},"heart":{"en":[],"ar":[]},"base":{"en":[],"ar":[]}}',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table product_images (
  id         bigint generated always as identity primary key,
  product_id bigint not null references products on delete cascade,
  path       text not null,                              -- path inside the product-images bucket
  position   int not null default 0                      -- 0 = cover
);

create table orders (
  id            bigint generated always as identity primary key,
  user_id       uuid references auth.users,              -- null for guest checkout
  customer_name text not null,
  phone         text not null,
  address       text not null,
  status        text not null default 'pending'
    check (status in ('pending','confirmed','shipped','delivered','cancelled')),
  total_egp     numeric(10,2) not null default 0,
  created_at    timestamptz not null default now()
);

create table order_items (
  id             bigint generated always as identity primary key,
  order_id       bigint not null references orders on delete cascade,
  product_id     bigint not null references products,
  qty            int not null check (qty > 0),
  unit_price_egp numeric(10,2) not null                  -- price at time of purchase
);

create table stock_movements (
  id         bigint generated always as identity primary key,
  product_id bigint not null references products,
  delta      int not null,
  reason     text not null check (reason in ('order','restock','adjustment','cancel')),
  order_id   bigint references orders,
  created_by uuid references auth.users,
  created_at timestamptz not null default now()
);

create index on products (status);
create index on product_images (product_id, position);
create index on order_items (order_id);
create index on orders (created_at desc);
create index on stock_movements (product_id);
create index on orders (user_id);
create index on order_items (product_id);
create index on stock_movements (order_id);

-- ---------- helpers ----------
create function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from profiles where id = auth.uid() and role = 'admin');
$$;

create function my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from profiles where id = auth.uid();
$$;

create function touch_updated_at() returns trigger language plpgsql set search_path = public as $$
begin new.updated_at = now(); return new; end $$;
create trigger products_touch before update on products for each row execute function touch_updated_at();

-- every new auth user gets a customer profile (admins are promoted by hand, see BACKEND.md)
create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id) values (new.id) on conflict do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users for each row execute function handle_new_user();

-- ---------- row level security ----------
alter table profiles        enable row level security;
alter table products        enable row level security;
alter table product_images  enable row level security;
alter table orders          enable row level security;
alter table order_items     enable row level security;
alter table stock_movements enable row level security;

-- storefront: everyone reads non-draft products; only admins write
create policy "read products"  on products for select using (status <> 'draft' or is_admin());
create policy "admin insert products" on products for insert with check (is_admin());
create policy "admin update products" on products for update using (is_admin()) with check (is_admin());
create policy "admin delete products" on products for delete using (is_admin());

create policy "read images" on product_images for select
  using (exists (select 1 from products p where p.id = product_id and (p.status <> 'draft' or is_admin())));
create policy "admin insert images" on product_images for insert with check (is_admin());
create policy "admin update images" on product_images for update using (is_admin()) with check (is_admin());
create policy "admin delete images" on product_images for delete using (is_admin());

-- orders are created only through place_order(); customers read their own, admins read/update all
create policy "read own orders"   on orders for select using (user_id = auth.uid() or is_admin());
create policy "admin update orders" on orders for update using (is_admin()) with check (is_admin());
create policy "read own order items" on order_items for select
  using (exists (select 1 from orders o where o.id = order_id and (o.user_id = auth.uid() or is_admin())));
create policy "admin read stock log" on stock_movements for select using (is_admin());

-- profiles: read yourself (admins read all); update yourself but never your role
create policy "read own profile" on profiles for select using (id = auth.uid() or is_admin());
create policy "update own profile" on profiles for update
  using (id = auth.uid()) with check (id = auth.uid() and role = my_role());

-- ---------- functions ----------
-- Place an order. Prices come from the database, stock is checked and reduced atomically.
create function place_order(p_name text, p_phone text, p_address text, p_items jsonb)
returns bigint language plpgsql security definer set search_path = public as $$
declare
  v_order bigint; v_total numeric := 0; it jsonb; prod products; v_qty int;
begin
  if length(trim(coalesce(p_name, ''))) < 2 or length(p_name) > 120 then raise exception 'Invalid name'; end if;
  if p_phone !~ '^[0-9+ ()-]{8,20}$' then raise exception 'Invalid phone number'; end if;
  if length(trim(coalesce(p_address, ''))) < 6 or length(p_address) > 500 then raise exception 'Invalid address'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) not between 1 and 30 then raise exception 'Invalid items'; end if;

  insert into orders (user_id, customer_name, phone, address)
  values (auth.uid(), trim(p_name), trim(p_phone), trim(p_address)) returning id into v_order;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 20 then raise exception 'Invalid quantity'; end if;
    select * into prod from products where id = (it->>'product_id')::bigint for update;
    if not found or prod.status <> 'published' then raise exception 'Product unavailable'; end if;
    if prod.stock is not null then
      if prod.stock < v_qty then raise exception 'Not enough stock for %', prod.name_en; end if;
      update products set stock = stock - v_qty where id = prod.id;
      insert into stock_movements (product_id, delta, reason, order_id) values (prod.id, -v_qty, 'order', v_order);
    end if;
    insert into order_items (order_id, product_id, qty, unit_price_egp) values (v_order, prod.id, v_qty, prod.price_egp);
    v_total := v_total + prod.price_egp * v_qty;
  end loop;

  update orders set total_egp = v_total where id = v_order;
  return v_order;
end $$;

-- Admin stock adjustment with an audit row. Returns the new stock.
create function adjust_stock(p_product bigint, p_delta int, p_reason text default 'adjustment')
returns int language plpgsql security definer set search_path = public as $$
declare v_stock int;
begin
  if not is_admin() then raise exception 'Not allowed'; end if;
  update products set stock = stock + p_delta where id = p_product and stock is not null returning stock into v_stock;
  if not found then raise exception 'Product not found or stock not tracked'; end if;
  insert into stock_movements (product_id, delta, reason, created_by) values (p_product, p_delta, p_reason, auth.uid());
  return v_stock;
end $$;

-- Cancelling an order puts the stock back (admin only; call after setting status to cancelled).
create function restock_cancelled_order(p_order bigint)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if not is_admin() then raise exception 'Not allowed'; end if;
  if not exists (select 1 from orders where id = p_order and status = 'cancelled') then raise exception 'Order is not cancelled'; end if;
  if exists (select 1 from stock_movements where order_id = p_order and reason = 'cancel') then return; end if;
  for r in select oi.product_id, oi.qty from order_items oi join products p on p.id = oi.product_id
           where oi.order_id = p_order and p.stock is not null loop
    update products set stock = stock + r.qty where id = r.product_id;
    insert into stock_movements (product_id, delta, reason, order_id, created_by) values (r.product_id, r.qty, 'cancel', p_order, auth.uid());
  end loop;
end $$;

revoke all on function place_order(text, text, text, jsonb) from public, anon, authenticated;
revoke all on function adjust_stock(bigint, int, text) from public, anon, authenticated;
revoke all on function restock_cancelled_order(bigint) from public, anon, authenticated;
revoke all on function is_admin() from public;
revoke all on function my_role() from public;
revoke all on function handle_new_user() from public, anon, authenticated;
grant execute on function place_order(text, text, text, jsonb) to anon, authenticated;
grant execute on function adjust_stock(bigint, int, text) to authenticated;
grant execute on function restock_cancelled_order(bigint) to authenticated;
-- RLS policies call these as anon too; they only report on the caller, so exposing them is safe
grant execute on function is_admin() to anon, authenticated;
grant execute on function my_role() to anon, authenticated;

